ALTER TABLE auth.account
    DROP CONSTRAINT IF EXISTS chk_account_identity;

ALTER TABLE auth.account
    ALTER COLUMN mobile SET NOT NULL;


CREATE SCHEMA IF NOT EXISTS legal;


CREATE TABLE legal.terms (
    id UUID NOT NULL DEFAULT gen_random_uuid(),
    content TEXT NOT NULL,
    version VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMPTZ,

    CONSTRAINT pk_terms
        PRIMARY KEY (id),

    CONSTRAINT uk_terms_version
        UNIQUE (version),

    CONSTRAINT chk_terms_status
        CHECK (
            status IN ('DRAFT', 'PUBLISHED', 'RETIRED')
        ),

    CONSTRAINT chk_terms_publication_state
        CHECK (
            (status = 'DRAFT' AND published_at IS NULL)
            OR
            (
                status IN ('PUBLISHED', 'RETIRED')
                AND published_at IS NOT NULL
            )
        )
);


CREATE UNIQUE INDEX uk_terms_single_published
    ON legal.terms (status)
    WHERE status = 'PUBLISHED';


CREATE TABLE legal.terms_acceptance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    account_id BIGINT NOT NULL,
    terms_id UUID NOT NULL,
    accepted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_terms_acceptance
        PRIMARY KEY (id),

    CONSTRAINT fk_terms_acceptance_account
        FOREIGN KEY (account_id)
        REFERENCES auth.account (id)
        ON DELETE NO ACTION,

    CONSTRAINT fk_terms_acceptance_terms
        FOREIGN KEY (terms_id)
        REFERENCES legal.terms (id)
        ON DELETE NO ACTION,

    CONSTRAINT uk_terms_acceptance_account_terms
        UNIQUE (account_id, terms_id)
);


CREATE SCHEMA IF NOT EXISTS customer;


CREATE TABLE customer.customer_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    account_id BIGINT NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_customer_profile
        PRIMARY KEY (id),

    CONSTRAINT fk_customer_profile_account
        FOREIGN KEY (account_id)
        REFERENCES auth.account (id)
        ON DELETE NO ACTION,

    CONSTRAINT uk_customer_profile_account
        UNIQUE (account_id),

    CONSTRAINT chk_customer_profile_full_name
        CHECK (char_length(btrim(full_name)) > 0)
);